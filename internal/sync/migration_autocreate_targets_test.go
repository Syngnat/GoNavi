func TestMapMySQLColumnToOracleLikeTypes(t *testing.T) {
	t.Parallel()

	cases := []struct {
		name      string
		col       connection.ColumnDefinition
		wantType  string
		wantIdent bool
	}{
		{"tinyint auto_increment", connection.ColumnDefinition{Name: "id", Type: "tinyint", Extra: "auto_increment"}, "SMALLINT", true},
		{"smallint auto_increment", connection.ColumnDefinition{Name: "id", Type: "smallint", Extra: "auto_increment"}, "SMALLINT", true},
		{"smallint unsigned auto_increment", connection.ColumnDefinition{Name: "id", Type: "smallint unsigned", Extra: "auto_increment"}, "INTEGER", true},
		{"int auto_increment", connection.ColumnDefinition{Name: "id", Type: "int", Extra: "auto_increment"}, "INTEGER", true},
		{"int unsigned auto_increment", connection.ColumnDefinition{Name: "id", Type: "int unsigned", Extra: "auto_increment"}, "BIGINT", true},
		{"bigint auto_increment", connection.ColumnDefinition{Name: "id", Type: "bigint", Extra: "auto_increment"}, "BIGINT", true},
		{"int unsigned", connection.ColumnDefinition{Name: "v", Type: "int unsigned"}, "NUMBER(10)", false},
		{"tinyint(1)", connection.ColumnDefinition{Name: "v", Type: "tinyint(1)"}, "NUMBER(1)", false},
		{"decimal", connection.ColumnDefinition{Name: "v", Type: "decimal(10,2)"}, "NUMBER(10,2)", false},
		{"text", connection.ColumnDefinition{Name: "v", Type: "text"}, "CLOB", false},
		{"json", connection.ColumnDefinition{Name: "v", Type: "json"}, "CLOB", false},
		{"blob", connection.ColumnDefinition{Name: "v", Type: "blob"}, "BLOB", false},
		{"enum", connection.ColumnDefinition{Name: "v", Type: "enum('a','b')"}, "VARCHAR(255)", false},
		{"date", connection.ColumnDefinition{Name: "v", Type: "date"}, "DATE", false},
		{"time", connection.ColumnDefinition{Name: "v", Type: "time"}, "TIMESTAMP", false},
	}
	for _, tc := range cases {
		gotType, gotIdent, warnings := mapMySQLColumnToOracleLike("dameng", tc.col)
		if gotType != tc.wantType {
			t.Errorf("%s: type = %q, want %q (warnings=%v)", tc.name, gotType, tc.wantType, warnings)
		}
		if gotIdent != tc.wantIdent {
			t.Errorf("%s: identity = %v, want %v", tc.name, gotIdent, tc.wantIdent)
		}
	}

	unsignedBigint := connection.ColumnDefinition{Name: "id", Type: "bigint unsigned", Extra: "auto_increment"}
	gotType, gotIdent, warnings := mapMySQLColumnToOracleLike("dameng", unsignedBigint)
	if gotType != "NUMBER(20)" || gotIdent {
		t.Fatalf("bigint unsigned auto_increment = (%q, identity=%v), want NUMBER(20) without identity", gotType, gotIdent)
	}
	if !strings.Contains(strings.Join(warnings, "\n"), "不迁移自增语义") {
		t.Fatalf("bigint unsigned auto_increment must warn before dropping identity: %v", warnings)
	}

	sqliteType, sqliteIdentity, sqliteWarnings := mapMySQLColumnToSQLite(unsignedBigint)
	if sqliteType != "NUMERIC" || sqliteIdentity {
		t.Fatalf("bigint unsigned auto_increment -> sqlite = (%q, identity=%v), want NUMERIC without autoincrement", sqliteType, sqliteIdentity)
	}
	if !strings.Contains(strings.Join(sqliteWarnings, "\n"), "无法覆盖其完整值域") {
		t.Fatalf("sqlite bigint unsigned auto_increment must warn about range loss: %v", sqliteWarnings)
	}

	// varchar 超 4000 上限降级 CLOB。
	overflowCol := connection.ColumnDefinition{Name: "big", Type: "varchar(8000)"}
	gotType, _, warnings = mapMySQLColumnToOracleLike("dameng", overflowCol)
	if gotType != "CLOB" {
		t.Fatalf("varchar(8000) should map to CLOB, got %q", gotType)
	}
	if len(warnings) == 0 {
		t.Fatalf("varchar(8000) should produce a warning")
	}
}

// 自增 tinyint(1) 的 (1) 是 MySQL 显示宽度，不是布尔约束。只有普通
// tinyint(1) 才能按 boolean 映射；自增列必须保留整数值域和生成语义。
func TestMySQLAutoIncrementColumnsDoNotUseBooleanFallback(t *testing.T) {
	t.Parallel()

	tinyAuto := connection.ColumnDefinition{Name: "id", Type: "tinyint(1)", Extra: "auto_increment"}
	pgType, pgIdentity, _ := mapMySQLColumnToKingbase(tinyAuto)
	if pgType != "smallint" || !pgIdentity {
		t.Fatalf("mysql tinyint(1) auto_increment -> pglike = (%q, identity=%v), want smallint identity", pgType, pgIdentity)
	}

	sqliteType, sqliteIdentity, _ := mapMySQLColumnToSQLite(tinyAuto)
	if sqliteType != "INTEGER" || !sqliteIdentity {
		t.Fatalf("mysql tinyint(1) auto_increment -> sqlite = (%q, identity=%v), want INTEGER autoincrement", sqliteType, sqliteIdentity)
	}

	oracleType, oracleIdentity, _ := mapMySQLColumnToOracleLike("oracle", tinyAuto)
	if oracleType != "NUMBER(5)" || !oracleIdentity {
		t.Fatalf("mysql tinyint(1) auto_increment -> oracle = (%q, identity=%v), want NUMBER(5) identity", oracleType, oracleIdentity)
	}

	for _, sourceType := range []string{"tinyint unsigned", "smallint unsigned", "int unsigned", "bigint unsigned"} {
		mappedType, useIdentity, warnings := mapMySQLColumnToOracleLike("oracle", connection.ColumnDefinition{
			Name: "id", Type: sourceType, Extra: "auto_increment",
		})
		if !useIdentity {
			t.Fatalf("mysql %s auto_increment -> oracle = %q without identity, warnings=%v", sourceType, mappedType, warnings)
		}
	}
}
