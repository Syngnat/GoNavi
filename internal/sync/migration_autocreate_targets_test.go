func TestLegacyAutoCreateCapabilityMatchesPlanner(t *testing.T) {
	t.Parallel()

	// capability 与真实 planner 必须一致：任何一个支持自动建表，另一个也要支持。
	for _, target := range []string{"dameng", "oracle", "iris", "sqlserver", "sqlite", "kingbase", "postgres", "mysql", "clickhouse"} {
		capability := ResolveMigrationCapability(
			connection.ConnectionConfig{Type: "mysql"},
			connection.ConnectionConfig{Type: target},
		)
		config := SyncConfig{
			SourceConfig:        connection.ConnectionConfig{Type: "mysql"},
			TargetConfig:        connection.ConnectionConfig{Type: target},
			TargetTableStrategy: "smart",
			SourceDatabase:      "db",
			TargetDatabase:      "db",
		}
		sourceDB := &fakeMigrationDB{columns: map[string][]connection.ColumnDefinition{
			"db.orders": {{Name: "id", Type: "bigint", Nullable: "NO", Key: "PRI"}},
		}}
		plan, _, _, err := buildSchemaMigrationPlan(config, "orders", sourceDB, &fakeMigrationDB{})
		if err != nil {
			t.Fatalf("target=%s plan error: %v", target, err)
		}
		if capability.SupportsAutoCreate != plan.AutoCreate {
			t.Fatalf("target=%s capability.supportsAutoCreate=%v but plan.AutoCreate=%v",
				target, capability.SupportsAutoCreate, plan.AutoCreate)
		}
		if capability.SupportsAutoCreate && plan.CreateTableSQL == "" {
			t.Fatalf("target=%s supportsAutoCreate but generated no CREATE TABLE", target)
		}
	}
}

func TestLegacyAutoCreateSQLServerPlan(t *testing.T) {
	t.Parallel()

	config := SyncConfig{
		SourceConfig:        connection.ConnectionConfig{Type: "mysql"},
		TargetConfig:        connection.ConnectionConfig{Type: "sqlserver"},
		TargetTableStrategy: "smart",
		SourceDatabase:      "db",
		TargetDatabase:      "db",
	}
	sourceDB := &fakeMigrationDB{columns: map[string][]connection.ColumnDefinition{
		"db.orders": {
			{Name: "id", Type: "int", Nullable: "NO", Key: "PRI", Extra: "auto_increment"},
			{Name: "title", Type: "varchar(5000)", Nullable: "YES"},
			{Name: "enabled", Type: "tinyint(1)", Nullable: "YES", Default: stringPtr("1")},
			{Name: "created_at", Type: "datetime", Nullable: "NO"},
		},
	}}
	plan, _, _, err := buildSchemaMigrationPlan(config, "orders", sourceDB, &fakeMigrationDB{})
	if err != nil {
		t.Fatalf("plan error: %v", err)
	}
	for _, fragment := range []string{
		// SQL Server 的 IDENTITY 列拒绝显式插入，自动建表建普通数字列保数据导入。
		`[id] INT NOT NULL`,
		// varchar(5000) 超 4000 上限降级 NVARCHAR(MAX)，并有 warning。
		`[title] NVARCHAR(MAX)`,
		`[enabled] BIT DEFAULT 1`,
		// datetime 不得被 date 前缀分支吞掉变成 DATE。
		`[created_at] DATETIME2 NOT NULL`,
	} {
		if !strings.Contains(plan.CreateTableSQL, fragment) {
			t.Fatalf("sqlserver DDL missing %q:\n%s", fragment, plan.CreateTableSQL)
		}
	}
	if strings.Contains(strings.ToUpper(plan.CreateTableSQL), "IDENTITY") {
		t.Fatalf("sqlserver DDL must not emit IDENTITY (explicit inserts would fail):\n%s", plan.CreateTableSQL)
	}
	joined := strings.Join(plan.Warnings, "\n")
	if !strings.Contains(joined, "IDENTITY 列不允许显式插入") {
		t.Fatalf("丢弃自增语义后未告警: %v", plan.Warnings)
	}
	if len(plan.Warnings) == 0 {
		t.Fatalf("expected varchar-overflow warning, got none")
	}
}

func TestLegacyAutoCreateSQLitePlan(t *testing.T) {
	t.Parallel()

	config := SyncConfig{
		SourceConfig:        connection.ConnectionConfig{Type: "mysql"},
		TargetConfig:        connection.ConnectionConfig{Type: "sqlite"},
		TargetTableStrategy: "smart",
		SourceDatabase:      "db",
		TargetDatabase:      "db",
	}
	sourceDB := &fakeMigrationDB{columns: map[string][]connection.ColumnDefinition{
		"db.orders": {
			{Name: "id", Type: "int", Nullable: "NO", Key: "PRI", Extra: "auto_increment"},
			{Name: "name", Type: "varchar(64)", Nullable: "NO"},
		},
	}}
	plan, _, _, err := buildSchemaMigrationPlan(config, "orders", sourceDB, &fakeMigrationDB{})
	if err != nil {
		t.Fatalf("plan error: %v", err)
	}
	// AUTOINCREMENT 已含 PRIMARY KEY，不得再追加重复约束。
	if !strings.Contains(plan.CreateTableSQL, `"id" INTEGER PRIMARY KEY AUTOINCREMENT`) {
		t.Fatalf("sqlite DDL missing autoincrement pk:\n%s", plan.CreateTableSQL)
	}
	if strings.Count(plan.CreateTableSQL, "PRIMARY KEY") != 1 {
		t.Fatalf("sqlite DDL declares PRIMARY KEY more than once:\n%s", plan.CreateTableSQL)
	}
	if !strings.Contains(plan.CreateTableSQL, `"name" TEXT NOT NULL`) {
		t.Fatalf("sqlite DDL missing NOT NULL:\n%s", plan.CreateTableSQL)
	}
}

