func scanSQLServerRowsWithMessages(ctx context.Context, rows *sql.Rows, retmsg *sqlexp.ReturnMessage) ([]connection.ResultSetData, []string, error) {
	if rows == nil {
		return []connection.ResultSetData{emptySQLServerRowsResultSet()}, nil, nil
	}
	if ctx == nil {
		ctx = context.Background()
	}

	var (
		resultSets  []connection.ResultSetData
		messages    []string
		allMessages []string
	)
	active := true
	for active {
		raw := retmsg.Message(ctx)
		switch msg := raw.(type) {
		case sqlexp.MsgNotice:
			text := strings.TrimSpace(fmt.Sprint(msg.Message))
			if text != "" {
				messages = append(messages, text)
				allMessages = append(allMessages, text)
			}
		case sqlexp.MsgNext:
			data, cols, err := scanRows(rows)
			if err != nil {
				return resultSets, messages, err
			}
			if data == nil {
				data = []map[string]interface{}{}
			}
			if cols == nil {
				cols = []string{}
			}
			resultSets = append(resultSets, connection.ResultSetData{
				Rows:     data,
				Columns:  cols,
				Messages: append([]string(nil), messages...),
			})
			messages = nil
		case sqlexp.MsgRowsAffected:
			resultSets = append(resultSets, connection.ResultSetData{
				Rows:     []map[string]interface{}{{"affectedRows": msg.Count}},
				Columns:  []string{"affectedRows"},
				Messages: append([]string(nil), messages...),
			})
			messages = nil
		case sqlexp.MsgNextResultSet:
			// Only MsgNext proves a row set is ready. Calling Columns at an empty
			// boundary drains later DONE and PRINT tokens in go-mssqldb Rowsq.
			active = rows.NextResultSet()
		case sqlexp.MsgError:
			return resultSets, messages, msg.Error
		default:
			active = false
		}
	}
	if len(messages) > 0 {
		resultSets = append(resultSets, connection.ResultSetData{
			Rows:     []map[string]interface{}{},
			Columns:  []string{},
			Messages: append([]string(nil), messages...),
		})
	}
	if len(resultSets) == 0 {
		resultSets = []connection.ResultSetData{emptySQLServerRowsResultSet()}
	}
	if err := rows.Err(); err != nil {
		return resultSets, allMessages, err
	}
	return resultSets, allMessages, nil
}

func emptySQLServerRowsResultSet() connection.ResultSetData {
	return connection.ResultSetData{
		Rows:    []map[string]interface{}{},
		Columns: []string{},
	}
}

// quoteBracket escapes ] in identifiers for safe use in SQL Server [bracket] notation
func quoteBracket(name string) string {
	return strings.ReplaceAll(name, "]", "]]")
}

// quoteSQLServerChangeIdentifier removes one existing bracket delimiter, then
// escapes the identifier contents exactly once for DML generated by the table
// editor.
func quoteSQLServerChangeIdentifier(name string) string {
	n := name
	trimmed := strings.TrimSpace(name)
	if len(trimmed) >= 2 && trimmed[0] == '[' && trimmed[len(trimmed)-1] == ']' {
		n = strings.ReplaceAll(trimmed[1:len(trimmed)-1], "]]", "]")
	}
	if strings.TrimSpace(n) == "" {
		return "[]"
	}
	return "[" + strings.ReplaceAll(n, "]", "]]") + "]"
}

func (s *SqlServerDB) getDSN(config connection.ConnectionConfig) string {
	// sqlserver://user:password@host:port?database=dbname
	dbname := config.Database
	if dbname == "" {
		dbname = "master"
	}

	u := &url.URL{
		Scheme: "sqlserver",
		Host:   net.JoinHostPort(config.Host, strconv.Itoa(config.Port)),
	}
	u.User = url.UserPassword(config.User, config.Password)

	q := url.Values{}
	q.Set("database", dbname)
	q.Set("connection timeout", strconv.Itoa(getConnectTimeoutSeconds(config)))
	encrypt, trustServerCertificate := resolveSQLServerTLSSettings(config)
	q.Set("encrypt", encrypt)
	q.Set("trustservercertificate", trustServerCertificate)
	if strings.TrimSpace(config.SSLCAPath) != "" {
		q.Set("certificate", strings.TrimSpace(config.SSLCAPath))
	}
	mergeConnectionParamsFromConfigWithAllowlist(q, config, sqlServerConnectionParamNames, "sqlserver")
	u.RawQuery = q.Encode()

	return u.String()
}

func (s *SqlServerDB) Connect(config connection.ConnectionConfig) (err error) {
	_ = s.Close()
	defer func() {
		if err != nil {
			_ = s.Close()
		}
	}()

	var dsn string

	if config.UseSSH {
		logger.Infof("SQL Server 使用 SSH 连接：地址=%s:%d 用户=%s", config.Host, config.Port, config.User)

		forwarder, err := ssh.AcquireLocalForwarder(config.SSH, config.Host, config.Port)
		if err != nil {
			return fmt.Errorf("创建 SSH 隧道失败：%w", err)
		}
		s.forwarder = forwarder

		host, portStr, err := net.SplitHostPort(forwarder.LocalAddr)
		if err != nil {
			return fmt.Errorf("解析本地转发地址失败：%w", err)
		}

		port, err := strconv.Atoi(portStr)
		if err != nil {
			return fmt.Errorf("解析本地端口失败：%w", err)
		}

		localConfig := config
		localConfig.Host = host
		localConfig.Port = port
		localConfig.UseSSH = false

		dsn = s.getDSN(localConfig)
		logger.Infof("SQL Server 通过本地端口转发连接：%s -> %s:%d", forwarder.LocalAddr, config.Host, config.Port)
	} else {
		dsn = s.getDSN(config)
	}

	db, err := sql.Open("sqlserver", dsn)
	if err != nil {
		return wrapDatabaseConnectionOpenError(err)
	}
	configureSQLConnectionPool(db, "sqlserver")
	s.conn = db
	s.pingTimeout = getConnectTimeout(config)

	verificationStartedAt := time.Now()
	if err := s.Ping(); err != nil {
		_ = db.Close()
		s.conn = nil
		if s.forwarder == nil {
			return wrapDatabaseConnectionVerifyError(err)
		}
		return wrapDatabaseConnectionVerifyErrorWithForwarder(err, s.forwarder, verificationStartedAt)
	}
	return nil
}

func (s *SqlServerDB) Close() error {
	if s.forwarder != nil {
		if err := s.forwarder.Release(); err != nil {
			logger.Warnf("关闭 SQL Server SSH 端口转发失败：%v", err)
		}
		s.forwarder = nil
	}

	if s.conn != nil {
		return s.conn.Close()
	}
	return nil
}

func (s *SqlServerDB) Ping() error {
	if s.conn == nil {
		return fmt.Errorf("连接未打开")
	}
	timeout := s.pingTimeout
	if timeout <= 0 {
		timeout = 5 * time.Second
	}
	ctx, cancel := utils.ContextWithTimeout(timeout)
	defer cancel()
	return s.conn.PingContext(ctx)
}

