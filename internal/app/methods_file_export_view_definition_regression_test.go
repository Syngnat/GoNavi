func TestDumpTableSQLRejectsNonViewTextFromViewDefinitionLookup(t *testing.T) {
	fake := &fakeSQLDumpExportDB{
		fakeExportQueryDB: fakeExportQueryDB{
			data: []map[string]interface{}{{"ddl": "Not a view"}},
			defs: []connection.ColumnDefinition{{Name: "id", Type: "bigint", Nullable: "NO"}},
		},
		createSQL: "-- SHOW CREATE TABLE not fully supported for PostgreSQL in this MVP.",
	}
	var output bytes.Buffer
	writer := bufio.NewWriter(&output)

	if err := dumpTableSQL(
		context.Background(),
		writer,
		fake,
		connection.ConnectionConfig{Type: "postgres"},
		"pms30app_db",
		"ts_overview.basic_area_code",
		true,
		false,
		map[string]string{},
	); err != nil {
		t.Fatalf("dumpTableSQL returned error: %v", err)
	}
	if err := writer.Flush(); err != nil {
		t.Fatalf("flush exported SQL: %v", err)
	}

	content := output.String()
	if strings.Contains(content, "Not a view") {
		t.Fatalf("driver error text must not be written into the export file: %s", content)
	}
	if !strings.Contains(content, `CREATE TABLE "ts_overview"."basic_area_code"`) {
		t.Fatalf("expected a table DDL fallback, got: %s", content)
	}
}

func TestExtractViewCreateSQLRejectsNonViewText(t *testing.T) {
	if got := extractViewCreateSQL(map[string]interface{}{"ddl": "Not a view"}); got != "" {
		t.Fatalf("extractViewCreateSQL returned %q for a non-view value", got)
	}
}

func TestExtractViewCreateSQLKeepsSupportedViewForms(t *testing.T) {
	tests := []struct {
		name string
		ddl  string
	}{
		{name: "postgres body", ddl: "SELECT id FROM files"},
		{name: "postgres CTE body", ddl: "WITH source AS (SELECT id FROM files) SELECT id FROM source"},
		{name: "sql server DDL", ddl: "CREATE VIEW [dbo].[v_files] AS SELECT id FROM files"},
		{name: "mysql DDL", ddl: "CREATE ALGORITHM=UNDEFINED VIEW `v_files` AS SELECT id FROM files"},
		{name: "oracle DDL", ddl: "CREATE OR REPLACE FORCE VIEW APP.V_FILES AS SELECT id FROM files"},
		{name: "materialized view DDL", ddl: "CREATE MATERIALIZED VIEW v_files AS SELECT id FROM files"},
		{name: "alter view DDL", ddl: "ALTER VIEW [dbo].[v_files] AS SELECT id FROM files"},
		{name: "leading comment", ddl: "-- generated by server\nCREATE VIEW v_files AS SELECT id FROM files"},
		{name: "leading block comment", ddl: "/* generated by server */\nCREATE VIEW v_files AS SELECT id FROM files"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			if got := extractViewCreateSQL(map[string]interface{}{"ddl": test.ddl}); got == "" {
				t.Fatalf("extractViewCreateSQL rejected a supported view definition: %q", test.ddl)
			}
		})
	}
}
